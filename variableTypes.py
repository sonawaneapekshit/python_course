# Variable naming rules
# 1. Start with a letter or underscore, not a digit.
# 2. Use meaningful names.
# 3. Use lowercase snake_case for ordinary variables, e.g. is_active_user.
# 4. Use only letters, digits, and underscores; do not use Python keywords.
# 5. Names are case-sensitive: user_count and User_Count are different.
# 6. Avoid shadowing built-in names such as list, str, and sum.
# 7. Use leading or trailing underscores only when a naming convention calls for them.
